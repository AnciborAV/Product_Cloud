package org.example.aav.model;

/** Этап 2: задаём категории товаров, чтобы выбирать только допустимые значения. Учебная последовательность. */
public enum Category {

    // Овощи: допустимая категория с названием и значком.
    VEGETABLES("Овощи", "🥕"),
    // Фрукты: допустимая категория с названием и значком.
    FRUITS("Фрукты", "🍎"),
    // Молочные продукты: допустимая категория с названием и значком.
    DAIRY("Молочные продукты", "🥛"),

    // Хлеб и выпечка: допустимая категория с названием и значком.
    BAKERY("Хлеб и выпечка", "🥐"),
    // Бакалея: допустимая категория с названием и значком.
    PANTRY("Бакалея", "🍯"),

    // Соки: допустимая категория с названием и значком.
    JUICES("Соки", "🧃"),
    // Вода: допустимая категория с названием и значком.
    WATER("Вода", "💧"),
    // Мясо и птица: допустимая категория с названием и значком.
    MEAT("Мясо и птица", "🍗"),

    // Рыба и морепродукты: допустимая категория с названием и значком.
    FISH("Рыба и морепродукты", "🐟"),
    // Сладости и орехи: допустимая категория с названием и значком.
    SWEETS("Сладости и орехи", "🍫");

    // Название для показа пользователю.
    private final String title;
    // Значок категории.
    private final String icon;

    /**
     * Создаёт объект и заполняет его начальными данными.
     * @param title название для показа пользователю
     * @param icon значок категории
     */
    Category(String title, String icon) {
        this.title = title;
        this.icon = icon;
    }

    /**
     * Возвращает название для показа пользователю.
     */
    public String getTitle() { return title; }
    /**
     * Возвращает значок категории.
     */
    public String getIcon() { return icon; }
}
